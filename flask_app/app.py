@app.post("/api/allocate")
def allocate_cohort():
    try:
        body = request.get_json(silent=True) or {}
        students = body.get("students")
        internships = body.get("internships")

        if not isinstance(students, list) or len(students) == 0:
            return jsonify({"error": "At least one student is required for allocation."}), 400
        if not isinstance(internships, list) or len(internships) == 0:
            return jsonify({"error": "At least one internship is required for allocation."}), 400

        ai = get_gemini_client()
        prompt = (
            "Evaluate every student against every internship role based on skill match "
            "(including semantic equivalents like SQL <-> PostgreSQL, CSS <-> Tailwind CSS), "
            "project relevance, GPA vs minGpa, and track preference.\n\n"
            f"For EACH student, return capability evaluations for ALL {len(internships)} internships "
            "(every single internshipId must be evaluated for every student so optimal seat allocation can be computed).\n"
            "Also provide a concise 2-sentence executiveInsight summarizing the overall cohort skill-to-role fit.\n\n"
            "Scoring calibration:\n"
            "- 90-100%: Meets or exceeds all Core and Important skills with directly relevant project proof.\n"
            "- 75-89%: Meets Core skills with minor gaps in Important/Preferred skills.\n"
            "- 55-74%: Partial overlap or strong adjacent fundamentals; needs ramp-up.\n"
            "- Below 55%: Significant missing Core skills.\n"
            "- Ensure matchedSkills contributionPercent values are realistic and notes are concise (under 8 words).\n"
            '- Ensure severity in missingSkills is strictly one of: "High", "Moderate", or "Minor".\n\n'
            f"STUDENTS:\n{json.dumps(students, indent=2)}\n\n"
            f"INTERNSHIPS:\n{json.dumps(internships, indent=2)}"
        )

        response = ai.models.generate_content(
            model=MODEL_NAME,
            contents=prompt,
            config=types.GenerateContentConfig(
                system_instruction=(
                    "You are an objective, precision technical talent allocation engine for university "
                    "internship placements. Evaluate capability percentages rigorously and consistently without inflation."
                ),
                thinking_config=types.ThinkingConfig(thinking_level=types.ThinkingLevel.LOW),
                response_mime_type="application/json",
                response_schema=types.Schema(
                    type=types.Type.OBJECT,
                    properties={
                        "studentEvaluations": types.Schema(
                            type=types.Type.ARRAY,
                            items=types.Schema(
                                type=types.Type.OBJECT,
                                properties={
                                    "studentId": types.Schema(type=types.Type.STRING),
                                    "internshipScores": types.Schema(
                                        type=types.Type.ARRAY,
                                        items=CAPABILITY_SCORE_SCHEMA,
                                    ),
                                },
                                required=["studentId", "internshipScores"],
                            ),
                        ),
                        "executiveInsight": types.Schema(type=types.Type.STRING),
                    },
                    required=["studentEvaluations", "executiveInsight"],
                ),
            ),
        )

        if not response.text:
            raise RuntimeError("Gemini returned an empty allocation response.")

        parsed = json.loads(response.text)
        scores_by_student: dict[str, list[dict[str, Any]]] = {}
        for item in parsed.get("studentEvaluations", []):
            stu_id = str(item.get("studentId", ""))
            scores_by_student[stu_id] = [
                sanitize_score(sc) for sc in item.get("internshipScores", [])
            ]

        allocations = assign_seats_from_capabilities(students, internships, scores_by_student)
        allocated_list = [a for a in allocations if a["status"] == "Allocated"]
        total_seats = sum(max(0, int(i.get("seats", 0))) for i in internships)
        avg_cap = (
            round(
                sum(a["assignedCapabilityPercent"] for a in allocated_list)
                / len(allocated_list)
            )
            if allocated_list
            else 0
        )
        placement_rate = round((len(allocated_list) / len(students)) * 100)

        return jsonify(
            {
                "allocations": allocations,
                "summary": {
                    "averageCapabilityPercent": avg_cap,
                    "placementRatePercent": placement_rate,
                    "totalSeatsFilled": len(allocated_list),
                    "totalSeatsAvailable": total_seats,
                    "executiveInsight": parsed.get("executiveInsight")
                    or f"Evaluated {len(students)} candidates across {len(internships)} internships.",
                    "evaluatedBy": MODEL_NAME,
                    "evaluatedAt": datetime.now().strftime("%H:%M"),
                },
            }
        )
    except Exception as exc:
        return jsonify({"error": str(exc)}), 500


@app.post("/api/evaluate-student")
def evaluate_student():
    try:
        body = request.get_json(silent=True) or {}
        student = body.get("student")
        internships = body.get("internships")

        if not student or not isinstance(internships, list) or len(internships) == 0:
            return jsonify({"error": "Student profile and internships list are required."}), 400

        ai = get_gemini_client()
        prompt = (
            f"Evaluate this single student against ALL {len(internships)} internships and return "
            "exact capability percentages, sub-scores, matchedSkills, missingSkills, and concise rationale for each internship.\n\n"
            f"STUDENT:\n{json.dumps(student, indent=2)}\n\n"
            f"INTERNSHIPS:\n{json.dumps(internships, indent=2)}"
        )

        response = ai.models.generate_content(
            model=MODEL_NAME,
            contents=prompt,
            config=types.GenerateContentConfig(
                system_instruction=(
                    "You are a precision technical talent evaluator. Return calibrated 0-100 capability "
                    "percentages for each internship based on concrete skill levels and project evidence."
                ),
                thinking_config=types.ThinkingConfig(thinking_level=types.ThinkingLevel.LOW),
                response_mime_type="application/json",
                response_schema=types.Schema(
                    type=types.Type.OBJECT,
                    properties={
                        "internshipScores": types.Schema(
                            type=types.Type.ARRAY,
                            items=CAPABILITY_SCORE_SCHEMA,
                        ),
                    },
                    required=["internshipScores"],
                ),
            ),
        )

        if not response.text:
            raise RuntimeError("Gemini returned an empty evaluation response.")

        parsed = json.loads(response.text)
        ranked_matches = sorted(
            [sanitize_score(sc) for sc in parsed.get("internshipScores", [])],
            key=lambda s: s["capabilityPercent"],
            reverse=True,
        )
        return jsonify({"studentId": student.get("id"), "rankedMatches": ranked_matches})
    except Exception as exc:
        return jsonify({"error": str(exc)}), 500


@app.post("/api/evaluate-role")
def evaluate_role():
    try:
        body = request.get_json(silent=True) or {}
        internship = body.get("internship")
        students = body.get("students")

        if not internship or not isinstance(students, list) or len(students) == 0:
            return jsonify({"error": "Internship role and at least one student are required."}), 400

        ai = get_gemini_client()
        prompt = (
            "Evaluate EVERY student in the list below against this single posted internship role "
            "and return calibrated 0-100 capability percentages, sub-scores, matchedSkills, "
            "missingSkills, and concise rationale for each student.\n\n"
            f"POSTED INTERNSHIP ROLE:\n{json.dumps(internship, indent=2)}\n\n"
            f"STUDENTS:\n{json.dumps(students, indent=2)}"
        )

        role_score_schema = types.Schema(
            type=types.Type.OBJECT,
            properties={
                "studentId": types.Schema(type=types.Type.STRING),
                "capabilityPercent": types.Schema(type=types.Type.INTEGER),
                "coreSkillMatchPercent": types.Schema(type=types.Type.INTEGER),
                "projectRelevancePercent": types.Schema(type=types.Type.INTEGER),
                "readinessPercent": types.Schema(type=types.Type.INTEGER),
                "matchedSkills": CAPABILITY_SCORE_SCHEMA.properties["matchedSkills"],
                "missingSkills": CAPABILITY_SCORE_SCHEMA.properties["missingSkills"],
                "aiRationale": types.Schema(type=types.Type.STRING),
            },
            required=[
                "studentId",
                "capabilityPercent",
                "coreSkillMatchPercent",
                "projectRelevancePercent",
                "readinessPercent",
                "matchedSkills",
                "missingSkills",
                "aiRationale",
            ],
        )

        response = ai.models.generate_content(
            model=MODEL_NAME,
            contents=prompt,
            config=types.GenerateContentConfig(
                system_instruction=(
                    "You are a precision technical talent evaluator for hiring recruiters. "
                    "Return calibrated 0-100 capability percentages for every student against the posted role."
                ),
                thinking_config=types.ThinkingConfig(thinking_level=types.ThinkingLevel.LOW),
                response_mime_type="application/json",
                response_schema=types.Schema(
                    type=types.Type.OBJECT,
                    properties={
                        "studentScores": types.Schema(
                            type=types.Type.ARRAY,
                            items=role_score_schema,
                        ),
                    },
                    required=["studentScores"],
                ),
            ),
        )

        if not response.text:
            raise RuntimeError("Gemini returned an empty role evaluation response.")

        parsed = json.loads(response.text)
        student_scores = []
        for sc in parsed.get("studentScores", []):
            sanitized = sanitize_score(sc, fallback_internship_id=internship.get("id"))
            sanitized["studentId"] = str(sc.get("studentId", ""))
            student_scores.append(sanitized)

        student_scores.sort(key=lambda s: s["capabilityPercent"], reverse=True)
        return jsonify({"internshipId": internship.get("id"), "studentScores": student_scores})
    except Exception as exc:
        return jsonify({"error": str(exc)}), 500


@app.post("/api/parse-resume")
def parse_resume():
    try:
        body = request.get_json(silent=True) or {}
        resume_text = str(body.get("resumeText", "")).strip()
        if len(resume_text) < 20:
            return jsonify({"error": "Please provide at least a short resume or project summary."}), 400

        ai = get_gemini_client()
        response = ai.models.generate_content(
            model=MODEL_NAME,
            contents=(
                "Extract structured student profile fields and technical skills "
                "(with proficiency 1-5 based on depth of evidence) from the following resume or bio text:\n\n"
                f"{resume_text}"
            ),
            config=types.GenerateContentConfig(
                system_instruction=(
                    "Extract factual student details and calibrate skill levels 1 (introductory) "
                    "to 5 (production/research mastery). Return valid JSON."
                ),
                thinking_config=types.ThinkingConfig(thinking_level=types.ThinkingLevel.LOW),
                response_mime_type="application/json",
                response_schema=types.Schema(
                    type=types.Type.OBJECT,
                    properties={
                        "name": types.Schema(type=types.Type.STRING),
                        "university": types.Schema(type=types.Type.STRING),
                        "major": types.Schema(type=types.Type.STRING),
                        "graduationYear": types.Schema(type=types.Type.INTEGER),
                        "gpa": types.Schema(type=types.Type.NUMBER),
                        "preferredTrack": types.Schema(type=types.Type.STRING),
                        "projectsSummary": types.Schema(type=types.Type.STRING),
                        "skills": types.Schema(
                            type=types.Type.ARRAY,
                            items=types.Schema(
                                type=types.Type.OBJECT,
                                properties={
                                    "name": types.Schema(type=types.Type.STRING),
                                    "level": types.Schema(type=types.Type.INTEGER),
                                },
                                required=["name", "level"],
                            ),
                        ),
                    },
                    required=[
                        "name",
                        "university",
                        "major",
                        "graduationYear",
                        "gpa",
                        "preferredTrack",
                        "projectsSummary",
                        "skills",
                    ],
                ),
            ),
        )

        if not response.text:
            raise RuntimeError("Gemini returned an empty parse response.")

        return jsonify(json.loads(response.text))
    except Exception as exc:
        return jsonify({"error": str(exc)}), 500


