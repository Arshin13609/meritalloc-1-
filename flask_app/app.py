def load_firebase_config() -> dict[str, Any]:
    """Load Firebase client configuration generated by AI Studio."""
    if FIREBASE_CONFIG_PATH.exists():
        return json.loads(FIREBASE_CONFIG_PATH.read_text(encoding="utf-8"))
    local_cfg = BASE_DIR / "firebase-applet-config.json"
    if local_cfg.exists():
        return json.loads(local_cfg.read_text(encoding="utf-8"))
    return {}


def get_gemini_client() -> genai.Client:
    """Create a server-side Google GenAI client using GEMINI_API_KEY."""
    api_key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not api_key or api_key == "MY_GEMINI_API_KEY":
        raise RuntimeError(
            "GEMINI_API_KEY is not configured. Set it in .env or environment variables."
        )
    return genai.Client(
        api_key=api_key,
        http_options=types.HttpOptions(headers={"User-Agent": "aistudio-build"}),
    )


def clamp_percent(value: Any) -> int:
    try:
        num = float(value)
    except (TypeError, ValueError):
        return 0
    if num != num:  # NaN check
        return 0
    return max(0, min(100, round(num)))


def normalize_severity(severity: Any) -> str:
    if severity in ("High", "Moderate", "Minor"):
        return str(severity)
    return "Moderate"


def sanitize_score(score: dict[str, Any], fallback_internship_id: str | None = None) -> dict[str, Any]:
    missing_skills = [
        {
            "skill": str(gap.get("skill", "")),
            "requiredLevel": int(gap.get("requiredLevel", 3)),
            "studentLevel": int(gap.get("studentLevel", 1)),
            "severity": normalize_severity(gap.get("severity")),
            "upskillingTip": str(gap.get("upskillingTip", "")),
        }
        for gap in (score.get("missingSkills") or [])
    ]
    matched_skills = [
        {
            "skill": str(m.get("skill", "")),
            "studentLevel": int(m.get("studentLevel", 1)),
            "requiredLevel": int(m.get("requiredLevel", 3)),
            "contributionPercent": clamp_percent(m.get("contributionPercent", 0)),
            "note": str(m.get("note", "")),
        }
        for m in (score.get("matchedSkills") or [])
    ]
    return {
        "internshipId": str(score.get("internshipId") or fallback_internship_id or ""),
        "capabilityPercent": clamp_percent(score.get("capabilityPercent", 0)),
        "coreSkillMatchPercent": clamp_percent(score.get("coreSkillMatchPercent", 0)),
        "projectRelevancePercent": clamp_percent(score.get("projectRelevancePercent", 0)),
        "readinessPercent": clamp_percent(score.get("readinessPercent", 0)),
        "matchedSkills": matched_skills,
        "missingSkills": missing_skills,
        "aiRationale": str(score.get("aiRationale", "")),
    }


def assign_seats_from_capabilities(
    students: list[dict[str, Any]],
    internships: list[dict[str, Any]],
    ai_scores_by_student: dict[str, list[dict[str, Any]]],
) -> list[dict[str, Any]]:
    """Deterministic seat allocator respecting internship capacity limits."""
    remaining_seats = {
        role["id"]: max(0, int(role.get("seats", 0))) for role in internships
    }
    internship_map = {role["id"]: role for role in internships}

    edges: list[dict[str, Any]] = []
    for student in students:
        stu_id = student["id"]
        pref_tokens = [
            tok for tok in str(student.get("preferredTrack", "")).lower().split() if len(tok) > 3
        ]
        for score in ai_scores_by_student.get(stu_id, []):
            role_id = score.get("internshipId", "")
            internship = internship_map.get(role_id)
            if not internship:
                continue
            role_text = f"{internship.get('title', '')} {internship.get('department', '')}".lower()
            pref_bonus = 2 if any(tok in role_text for tok in pref_tokens) else 0
            edges.append(
                {
                    "studentId": stu_id,
                    "internshipId": role_id,
                    "capabilityPercent": clamp_percent(score.get("capabilityPercent", 0)),
                    "preferenceBonus": pref_bonus,
                }
            )

    edges.sort(
        key=lambda e: e["capabilityPercent"] + e["preferenceBonus"],
        reverse=True,
    )

    assigned_by_student: dict[str, dict[str, Any]] = {}
    for edge in edges:
        stu_id = edge["studentId"]
        role_id = edge["internshipId"]
        if stu_id in assigned_by_student:
            continue
        seats_left = remaining_seats.get(role_id, 0)
        if seats_left <= 0 or edge["capabilityPercent"] < 45:
            continue
        assigned_by_student[stu_id] = {
            "internshipId": role_id,
            "capability": edge["capabilityPercent"],
        }
        remaining_seats[role_id] = seats_left - 1

    allocations: list[dict[str, Any]] = []
    for student in students:
        stu_id = student["id"]
        ranked = sorted(
            ai_scores_by_student.get(stu_id, []),
            key=lambda s: s.get("capabilityPercent", 0),
            reverse=True,
        )
        assigned = assigned_by_student.get(stu_id)
        top_score = ranked[0]["capabilityPercent"] if ranked else 0

        if assigned:
            allocations.append(
                {
                    "studentId": stu_id,
                    "assignedInternshipId": assigned["internshipId"],
                    "status": "Allocated",
                    "assignedCapabilityPercent": assigned["capability"],
                    "rankedMatches": ranked,
                }
            )
        else:
            allocations.append(
                {
                    "studentId": stu_id,
                    "assignedInternshipId": None,
                    "status": "Waitlisted" if top_score >= 55 else "Unmatched",
                    "assignedCapabilityPercent": top_score,
                    "rankedMatches": ranked,
                }
            )
    return allocations


